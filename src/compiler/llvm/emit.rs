//! LLVM IR module assembly and C `main` entrypoint generation.

use crate::compiler::OptLevel;
use crate::compiler::llvm::codegen::{
    FunctionEmitter, LlvmModuleCollector, emit_string_constants, emit_user_globals,
};
use crate::compiler::llvm::runtime::{RuntimeMode, emit_runtime_prelude};
use crate::compiler::llvm::target::TargetSpec;
use crate::compiler::mir::MirProgram;

/// How a module is emitted.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct LlvmOptions {
    pub runtime: RuntimeMode,
    /// The `target triple` / `target datalayout` header; none when `None`.
    pub target: Option<TargetSpec>,
}

/// Emits standalone textual LLVM IR (`.ll`) for a compiled [`MirProgram`],
/// with the built-in runtime and no target header.
pub fn emit_llvm_ir(program: &MirProgram, opt_level: OptLevel) -> String {
    emit_llvm_ir_with(program, opt_level, &LlvmOptions::default())
}

/// Emits textual LLVM IR (`.ll`) for a compiled [`MirProgram`].
pub fn emit_llvm_ir_with(
    program: &MirProgram,
    opt_level: OptLevel,
    options: &LlvmOptions,
) -> String {
    let mut collector = LlvmModuleCollector::new();
    collector.collect_program(program);

    let mut fn_ir = String::new();
    let emitter = FunctionEmitter::new(&mut collector, 0);
    fn_ir.push_str(&emitter.emit_body(&program.main, "nyk_main"));

    let opt_note = match opt_level {
        OptLevel::O0 => "-O0",
        OptLevel::O1 => "-O1",
    };
    let runtime_note = match options.runtime {
        RuntimeMode::Builtin => "built-in runtime",
        RuntimeMode::Extern => "external runtime",
    };

    let mut out = format!(
        "; Generated by neyuki compiler LLVM backend ({}, {})\n",
        opt_note, runtime_note
    );
    if let Some(target) = &options.target {
        out.push_str(&target.header());
    }
    out.push('\n');
    emit_runtime_prelude(&mut out, options.runtime);
    out.push_str(&emit_string_constants(&collector.string_literals));
    out.push_str(&emit_user_globals(&collector.user_globals));
    out.push_str(&fn_ir);
    out.push_str(
        r#"
define i32 @main() {
entry:
  %res = call i32 @nyk_main(ptr @nyk_main.closure, ptr null, i32 0)
  ret i32 0
}
"#,
    );
    out
}
